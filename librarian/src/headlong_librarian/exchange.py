"""Export, import, stats and the offline eval set.

Export writes two kinds of mirror: the identity-scoped markdown mirror the
dashboard reads (``lib-<type>-<ulid>.md`` with ``bin/mem``-shaped scalar
frontmatter), and the human-facing project mirrors (``skills/``,
``addenda.md``, ``librarian.md``) that get committed with ``project/``.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from . import db, gate, identity, lifecycle, model, pack, queue, triggers

GENERATED = "<!-- generated by librarian export from node {id}; change it with `librarian propose --supersedes {id}` -->"
GENERATED_RE = re.compile(r"<!-- generated by librarian export")


def _slug(text: str, n: int = 48) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")
    return (s or "node")[:n]


def _yaml_scalar(v) -> str:
    s = str(v if v is not None else "")
    if s == "" or re.search(r"[:#\n\"']|^\s|\s$", s):
        return json.dumps(s)
    return s


def node_markdown(node: model.Node) -> str:
    fm = {
        "id": node.id,
        "summary": node.summary[:200],
        "type": node.type,
        "created": node.created.replace("T", " ").rstrip("Z"),
        "status": node.status,
        "tags": ", ".join(node.tags),
        "confidence": f"{node.confidence:.2f}",
        "project": node.project or "",
        "last_confirmed": node.last_confirmed or "",
    }
    lines = ["---"] + [f"{k}: {_yaml_scalar(v)}" for k, v in fm.items() if v != ""] + ["---", "", node.summary, ""]
    if node.body and node.body.strip() != node.summary.strip():
        lines += [node.body, ""]
    if node.outcome:
        lines += [f"Outcome: {node.outcome.get('value')} ({node.outcome.get('criterion', '')})", ""]
    if node.edges:
        lines.append("Edges:")
        lines += [f"- {e['type']} → {e['to']}" + (f" (w={e['weight']})" if e.get("weight") not in (None, 1.0) else "") for e in node.edges]
        lines.append("")
    if node.provenance:
        lines.append("Provenance: " + json.dumps(node.provenance, sort_keys=True))
    return "\n".join(lines) + "\n"


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)


def export_store(store: db.Store, out_dir: Path, fmt: str = "md", project_dir: Optional[Path] = None, project: Optional[str] = None) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    nodes = model.nodes_where(store, "1=1 ORDER BY created")
    written = 0
    if fmt == "json":
        lines = []
        for n in nodes:
            n.edges = model.node_edges(store, n.id)
            lines.append(json.dumps(n.to_json(), sort_keys=True))
        _atomic_write(out_dir / "nodes.jsonl", "\n".join(lines) + ("\n" if lines else ""))
        written = len(lines)
    else:
        existing = {p.name for p in out_dir.glob("lib-*.md")}
        for n in nodes:
            n.edges = model.node_edges(store, n.id)
            name = f"lib-{n.type.replace('_', '-')}-{n.id}.md"
            _atomic_write(out_dir / name, node_markdown(n))
            existing.discard(name)
            written += 1
        for stale in existing:
            try:
                (out_dir / stale).unlink()
            except OSError:
                pass
    report = {"dir": str(out_dir), "format": fmt, "written": written}
    if project_dir is not None:
        report["project"] = export_project(store, Path(project_dir), project)
    return report


def _skill_file(n: model.Node) -> str:
    head = GENERATED.format(id=n.id)
    tags = " ".join(n.tags)
    return f"{head}\n# {n.summary}\n\nStatus: {n.status} · confidence {n.confidence:.2f} · tags: {tags}\n\n{n.body}\n"


def export_project(store: db.Store, pdir: Path, project: Optional[str]) -> dict:
    counts = {"skills_project": 0, "skills_generic": 0}
    skills = model.nodes_where(store, "type = 'skill' AND status IN ('active','probationary','disputed') ORDER BY created")
    for sub in ("skills/project", "skills/generic"):
        d = pdir / sub
        d.mkdir(parents=True, exist_ok=True)
        for p in d.glob("*.md"):
            try:
                if GENERATED_RE.search(p.read_text()[:200]):
                    p.unlink()
            except OSError:
                pass
    for n in skills:
        generic = "scope:generic" in n.tags or "scope:general" in n.tags
        mine = project is not None and n.project == project
        if not (generic or mine):
            continue
        sub = "skills/generic" if generic else "skills/project"
        _atomic_write(pdir / sub / f"{_slug(n.summary)}-{n.id[-6:].lower()}.md", _skill_file(n))
        counts["skills_generic" if generic else "skills_project"] += 1
    # addenda.md: the working identity, read-only mirror.
    working = identity.list_identity(store, "working")
    core = identity.list_identity(store, "core")
    lines = [
        "# Addenda to the charter (working identity)",
        "",
        "Generated by `librarian export`: a read-only mirror of the agent's working-identity nodes.",
        "Change them with `librarian identity edit`; a human approves core changes via the check-in queue.",
        "",
        "## Core (human-approved)",
    ]
    lines += [f"- {n.id} · {n.body or n.summary}" for n in core] or ["- (none)"]
    lines += ["", "## Working (agent-maintained)"]
    lines += [f"- {n.id} · {n.status} · {n.body or n.summary}" for n in working] or ["- (none)"]
    _atomic_write(pdir / "addenda.md", "\n".join(lines) + "\n")
    # librarian.md: this project's digest.
    digest = project_digest(store, project)
    _atomic_write(pdir / "librarian.md", digest)
    counts["working"] = len(working)
    counts["core"] = len(core)
    return counts


def project_digest(store: db.Store, project: Optional[str]) -> str:
    where = "project = ?" if project else "1=1"
    params: tuple = (project,) if project else ()
    out = [f"# Librarian digest{' for ' + project if project else ''}", "", "Generated every wake by `librarian export`. The store is the record; this is a view of it.", ""]

    def section(title: str, nodes: list[model.Node], fmt) -> None:
        out.append(f"## {title} ({len(nodes)})")
        out.append("")
        out.extend(fmt(n) for n in nodes[:40])
        if len(nodes) > 40:
            out.append(f"- … {len(nodes) - 40} more (`librarian search --type …`)")
        out.append("")

    section("Decisions", model.nodes_where(store, f"type = 'decision' AND status IN ('active','probationary','disputed') AND {where} ORDER BY created DESC", params),
            lambda n: f"- {n.id} · {n.status} · {n.summary}")
    section("Retrospectives", model.nodes_where(store, f"type = 'retrospective' AND status IN ('active','probationary','disputed') AND {where} ORDER BY created DESC", params),
            lambda n: f"- {n.id} · {n.status} · {n.summary}")
    section("Skills", model.nodes_where(store, f"type = 'skill' AND status IN ('active','probationary','disputed') AND {where} ORDER BY created DESC", params),
            lambda n: f"- {n.id} · {n.status} · {n.summary}")
    eps = model.nodes_where(store, f"type = 'episode' AND {where} ORDER BY created DESC", params)
    section("Episodes (latest first)", eps,
            lambda n: f"- {n.created} · {(n.outcome or {}).get('value', '?')} ({(n.outcome or {}).get('criterion', '')}) · {n.summary[:120]}")
    items = queue.list_items(store, "pending")
    out.append(f"## Open check-in items ({len(items)})")
    out.append("")
    out.extend(f"- {i['id']} · {i['kind']} · {str((i.get('payload') or {}).get('summary') or (i.get('payload') or {}).get('tag') or '')[:100]}" for i in items)
    out.append("")
    s = stats(store, project=project)
    out.append("## Stats")
    out.append("")
    out.append(f"- nodes: {s['nodes']['total']} ({s['nodes']['by_status']})")
    out.append(f"- pack precision: {s['pack_precision']} · uncovered pulls: {s['uncovered_pull_rate']} · truncation: {s['truncation_rate']}")
    out.append("")
    return "\n".join(out)


# ── import ───────────────────────────────────────────────────────────────────


@dataclass
class ImportReport:
    stored: list[str] = field(default_factory=list)
    merged: list[str] = field(default_factory=list)
    rejected: list[dict] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {"stored": self.stored, "merged": self.merged, "rejected": self.rejected, "counts": {"stored": len(self.stored), "merged": len(self.merged), "rejected": len(self.rejected)}}


def _apply(store: db.Store, cand: gate.Candidate, rep: ImportReport, label: str, dry_run: bool) -> None:
    if dry_run:
        reasons = gate.check(store, cand)
        if reasons:
            rep.rejected.append({"summary": label, "reasons": reasons})
        else:
            rep.stored.append(label)
        return
    res = gate.apply(store, cand)
    if res.action == "merged":
        rep.merged.append(res.merge_target or label)
    elif res.accepted and res.id:
        rep.stored.append(res.id)
    else:
        rep.rejected.append({"summary": label, "reasons": res.reasons})


def import_json(store: db.Store, path: Path, author: Optional[str], status: Optional[str], dry_run: bool) -> ImportReport:
    rep = ImportReport()
    data = json.loads(path.read_text())
    nodes = data.get("nodes") if isinstance(data, dict) else data
    for raw in nodes or []:
        prov = dict(raw.get("provenance") or {})
        prov.setdefault("author", author or "human")
        prov.setdefault("method", "import")
        edges = [{"type": e["type"], "to": e["to"], "weight": e.get("weight", 1.0)} for e in raw.get("edges", []) if e.get("type") != "supersedes"]
        supersedes = next((e["to"] for e in raw.get("edges", []) if e.get("type") == "supersedes" and model.get_node(store, str(e["to"]), with_edges=False) is not None), None)
        cand = gate.Candidate(
            type=raw["type"],
            summary=raw["summary"],
            body=raw.get("body", ""),
            tags=raw.get("tags", []),
            provenance=prov,
            confidence=float(raw.get("confidence", 0.5)),
            valid_from=raw.get("valid_from"),
            valid_to=raw.get("valid_to"),
            project=raw.get("project"),
            status=(status or raw.get("status")) if (status or raw.get("status")) not in ("superseded", None) else None,
            edges=edges,
            outcome=raw.get("outcome"),
            id=raw.get("id"),
            supersedes=supersedes,
        )
        _apply(store, cand, rep, raw["summary"][:80], dry_run)
    return rep


def import_preferences(store: db.Store, path: Path, tags: list[str], author: str = "human", dry_run: bool = False) -> ImportReport:
    """One bullet = one preference node, the human's words verbatim; ``area:`` from the nearest heading."""
    rep = ImportReport()
    base = model.parse_tags(tags) or [f"team:{_slug(path.stem, 24)}"]
    area: Optional[str] = None
    for line in path.read_text().splitlines():
        h = re.match(r"^#+\s+(.+)$", line)
        if h:
            cand_area = "area:" + _slug(h.group(1), 24)
            area = cand_area if model.vocab_status(store, cand_area) == "active" else None
            continue
        m = re.match(r"^\s*[-*]\s+(.+)$", line)
        if not m:
            continue
        text = m.group(1).strip()
        if not text:
            continue
        t = list(base) + ([area] if area else [])
        cand = gate.Candidate(
            type="preference",
            summary=model.first_sentence(text)[:240] or text[:240],
            body=text,
            tags=t,
            provenance={"author": author, "method": "stated-value", "source": str(path.name)},
            confidence=0.9,
            status="active" if author == "human" else None,
        )
        _apply(store, cand, rep, text[:80], dry_run)
    return rep


def import_skills(store: db.Store, directory: Path, project: Optional[str], generic: bool, author: str = "main", dry_run: bool = False) -> ImportReport:
    rep = ImportReport()
    for p in sorted(directory.glob("*.md")):
        text = p.read_text()
        if GENERATED_RE.search(text[:200]) or p.name == ".keep":
            continue
        lines = [ln for ln in text.splitlines() if ln.strip()]
        if not lines:
            continue
        title = re.sub(r"^#+\s*", "", lines[0]).strip()
        body = "\n".join(text.splitlines()[1:]).strip() or title
        tags = ["scope:generic", "area:process"] if generic else ["area:process"]
        cand = gate.Candidate(
            type="skill",
            summary=title[:240],
            body=body,
            tags=tags,
            provenance={"author": author, "method": "import", "source": str(p)},
            project=None if generic else project,
            confidence=0.5,
        )
        _apply(store, cand, rep, title[:80], dry_run)
    return rep


def import_addenda(store: db.Store, path: Path, project: Optional[str], dry_run: bool = False) -> ImportReport:
    """Existing ``addenda.md`` entries become working-identity nodes (latest first, within the bound)."""
    rep = ImportReport()
    text = path.read_text()
    if GENERATED_RE.search(text[:400]) or "Generated by `librarian export`" in text[:400]:
        return rep
    entries = re.split(r"^###\s+", text, flags=re.M)[1:]
    for e in reversed(entries[-identity.WORKING_MAX_NODES :]):
        head, _, body = e.partition("\n")
        change = re.search(r"^Change:\s*(.+)$", body, re.M)
        summary = (change.group(1) if change else head).strip()
        if not summary:
            continue
        cand = gate.Candidate(
            type="identity_working",
            summary=summary[:240],
            body=body.strip()[:1200],
            tags=["scope:identity"],
            provenance={"author": "main", "method": "import", "source": "addenda.md", "title": head.strip()},
            confidence=0.6,
            project=project,
        )
        _apply(store, cand, rep, head[:80], dry_run)
    return rep


# ── stats ────────────────────────────────────────────────────────────────────


def stats(store: db.Store, since: Optional[str] = None, project: Optional[str] = None, week: Optional[str] = None) -> dict:
    where = "1=1"
    params: list = []
    if project:
        where += " AND project = ?"
        params.append(project)
    if since:
        where += " AND ts >= ?"
        params.append(since)
    out: dict = {}
    by_status = {r[0]: r[1] for r in store.q("SELECT status, COUNT(*) FROM nodes GROUP BY status")}
    by_type = {r[0]: r[1] for r in store.q("SELECT type, COUNT(*) FROM nodes GROUP BY type")}
    out["nodes"] = {"total": sum(by_status.values()), "by_status": by_status, "by_type": by_type}
    # Pack precision: task-section pack rows whose episode closed with success.
    rows = store.q(
        f"SELECT rl.node_id, rl.request_id FROM retrieval_log rl JOIN requests r ON r.request_id = rl.request_id "  # noqa: S608
        f"WHERE rl.source = 'pack' AND rl.section = 'task' AND {where.replace('project', 'r.project').replace('ts', 'r.ts')}",
        tuple(params),
    )
    packed = len(rows)
    cited_success = 0
    helpful = 0
    for r in rows:
        c = store.q1(
            "SELECT c.helpful, n.outcome FROM citations c JOIN nodes n ON n.id = c.episode_id WHERE c.node_id = ? AND c.request_id = ?",
            (r["node_id"], r["request_id"]),
        )
        if c is None:
            continue
        try:
            oc = json.loads(c["outcome"] or "{}").get("value")
        except ValueError:
            oc = None
        if oc == "success":
            cited_success += 1
        if c["helpful"]:
            helpful += 1
    out["pack_precision"] = round(cited_success / packed, 3) if packed else None
    out["helpful_rate"] = round(helpful / packed, 3) if packed else None
    pulls = store.q(f"SELECT covered_by_pack FROM requests WHERE kind IN ('search','fetch') AND {where}", tuple(params))  # noqa: S608
    unc = sum(1 for p in pulls if p[0] == 0)
    out["uncovered_pull_rate"] = round(unc / len(pulls), 3) if pulls else None
    packs = store.q(f"SELECT budget, used_tokens, truncated, llm_cut FROM requests WHERE kind = 'pack' AND {where}", tuple(params))  # noqa: S608
    out["packs"] = len(packs)
    out["budget_utilization"] = round(sum((p[1] or 0) for p in packs) / max(1, sum((p[0] or 0) for p in packs)), 3) if packs else None
    out["truncation_rate"] = round(sum(p[2] for p in packs) / len(packs), 3) if packs else None
    out["llm_cut_rate"] = round(sum(p[3] for p in packs) / len(packs), 3) if packs else None
    out["suggestions"] = triggers.acceptance(store)
    last = store.q1("SELECT report FROM consolidation_log WHERE step = 'merge' ORDER BY id DESC LIMIT 1")
    out["duplicate_pairs_last_run"] = json.loads(last[0]).get("duplicate_pairs") if last else None
    ref = db.now()
    old_disputed = [r[0] for r in store.q("SELECT id, created FROM nodes WHERE status = 'disputed'") if (db.age_days(r[1], ref) or 0) > 30]
    out["disputed_over_30d"] = len(old_disputed)
    prob = store.q("SELECT created FROM nodes WHERE status = 'probationary'")
    ages = sorted((db.age_days(r[0], ref) or 0.0) for r in prob)
    out["probationary"] = {"count": len(ages), "median_age_days": round(ages[len(ages) // 2], 1) if ages else None}
    out["queue_pending"] = queue.pending_count(store)
    out["pending_capture"] = store.q1("SELECT COUNT(*) FROM pending_capture WHERE cleared IS NULL")[0]
    out["review_flagged"] = [r[0] for r in store.q("SELECT id FROM nodes WHERE review_flag IS NOT NULL AND status IN ('active','probationary','disputed')")]
    # Skill reuse: repeated-failure suggestions whose skill was later cited in a success.
    sugg = store.q("SELECT memory_ids, response FROM suggestions WHERE trigger = 'repeated_failure'")
    out["skill_reuse"] = {"repeated_failure_suggestions": len(sugg), "accepted": sum(1 for s in sugg if s[1] == "accept")}
    if week:
        out["week"] = week
        prop = store.q("SELECT COUNT(*) FROM nodes WHERE provenance LIKE '%\"author\": \"main\"%'")
        out["proposed_by_agent_total"] = prop[0][0] if prop else 0
    # Spend by librarian role, from the usage ledger when present.
    ledger = os.environ.get("LLM_USAGE_LEDGER") or (os.path.join(os.environ.get("IDENTITY_DIR", ""), "usage", "llm.jsonl") if os.environ.get("IDENTITY_DIR") else "")
    spend: dict = {}
    if ledger and os.path.exists(ledger):
        try:
            with open(ledger) as fh:
                for line in fh:
                    try:
                        rec = json.loads(line)
                    except ValueError:
                        continue
                    rid = str(rec.get("run_id") or "")
                    if rid.startswith("librarian"):
                        d = spend.setdefault(rid, {"calls": 0, "in_tok": 0, "out_tok": 0, "cost_usd": 0.0})
                        d["calls"] += 1
                        d["in_tok"] += int(rec.get("in_tok") or 0)
                        d["out_tok"] += int(rec.get("out_tok") or 0)
                        d["cost_usd"] += float(rec.get("cost_usd") or 0.0)
        except OSError:
            pass
    out["librarian_spend"] = spend
    return out


# ── offline eval ─────────────────────────────────────────────────────────────


def run_eval(store: db.Store, eval_dir: Path, budget: Optional[int] = None, use_llm: bool = False) -> dict:
    cases = []
    for p in sorted(eval_dir.glob("*.json")):
        case = json.loads(p.read_text())
        req = pack.PackRequest(
            task=case.get("task", ""),
            tags=case.get("tags", []),
            project=case.get("project"),
            phase=case.get("phase"),
            budget=int(budget or case.get("budget", 4000)),
            log=False,
            use_llm=use_llm,
        )
        pk = pack.build(store, req)
        got = pk.ids("task")
        expected = set(case.get("expected", []))
        acceptable = set(case.get("acceptable", [])) | expected
        hit_ok = [g for g in got if g in acceptable]
        hit_exp = [g for g in got if g in expected]
        precision = len(hit_ok) / len(got) if got else 0.0
        recall_v = len(hit_exp) / len(expected) if expected else 1.0
        cases.append(
            {
                "id": case.get("id", p.stem),
                "precision": round(precision, 3),
                "recall": round(recall_v, 3),
                "got": got,
                "missed": sorted(expected - set(got)),
                "llm_cut": pk.llm_cut,
            }
        )
    n = len(cases)
    return {
        "cases": cases,
        "macro_precision": round(sum(c["precision"] for c in cases) / n, 3) if n else None,
        "macro_recall": round(sum(c["recall"] for c in cases) / n, 3) if n else None,
        "n": n,
    }


